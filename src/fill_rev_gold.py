    (0, "前次 盈利3,500–5,250万 → 盈利1,634万"),
    (0, "前次 盈利5,250–7,000万 → 亏损4,000–6,000万"),
    (4, "前次 3,500–5,200万 → 8,000–11,600万"),
    (0, "前次 7,500–14,000万 → 亏损38,000–45,000万"),
    (3, "前次 亏损6.93–3.95亿 → 亏损5.35–2.15亿（收窄约31%）"),
